let currentLanguage = 'pt';
export function setLanguage(lang) {
    console.log('setLanguage called with:', lang); // Debug log
    if (translations[lang]) {
        currentLanguage = lang;
        localStorage.setItem('language', lang);
        document.documentElement.lang = lang;
        console.log('Updating UI text for language:', lang); // Debug log
        updateUIText();
        window.dispatchEvent(new Event('languageChange')); // Trigger UI refresh
    }
    else {
        console.warn('Invalid language:', lang); // Debug log
    }
}
export function getCurrentLanguage() {
    return currentLanguage;
}
export function getTranslation(key) {
    const translation = translations[currentLanguage][key];
    if (!translation) {
        console.warn(`Translation key "${key}" not found for language "${currentLanguage}"`); // Debug log
    }
    return translation || key;
}
function updateUIText() {
    console.log('Updating UI elements with data-i18n'); // Debug log
    const elements = document.querySelectorAll('[data-i18n]');
    console.log('Found', elements.length, 'elements with data-i18n'); // Debug log
    elements.forEach((element) => {
        const key = element.getAttribute('data-i18n');
        if (key) {
            const translation = getTranslation(key);
            if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                element.placeholder = translation;
            }
            else {
                element.textContent = translation;
            }
        }
    });
    const titleElement = document.querySelector('title[data-i18n]');
    if (titleElement) {
        const titleKey = titleElement.getAttribute('data-i18n');
        if (titleKey) {
            console.log('Updating document title to:', getTranslation(titleKey)); // Debug log
            document.title = getTranslation(titleKey);
        }
    }
}
export function initializeLanguage() {
    console.log('Initializing language'); // Debug log
    const savedLang = localStorage.getItem('language');
    if (savedLang && translations[savedLang]) {
        currentLanguage = savedLang;
    }
    else {
        currentLanguage = 'pt';
        localStorage.setItem('language', 'pt');
    }
    document.documentElement.lang = currentLanguage;
    updateUIText();
}
